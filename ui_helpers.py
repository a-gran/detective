# Берем функции выхода из отдельного файла, чтобы ui_helpers.py отвечал только за вывод и ввод.
from exit_helpers import add_exit_text_to_prompt, check_exit_command


# Создаем функцию, которая печатает линию-разделитель.
def print_separator():
    # Печатаем в консоль строку из 60 черточек, чтобы красиво отделить один блок текста от другого.
    print("-" * 60)


# Создаем функцию, которая красиво печатает заголовок блока.
def print_title(title):
    # Печатаем пустую строку перед заголовком, чтобы новый блок не слипался с прошлым текстом.
    print()
    # Печатаем сам заголовок, чтобы игрок понял, какой раздел сейчас открыт.
    print(title)
    # Печатаем разделитель под заголовком, чтобы экран выглядел аккуратнее.
    print_separator()


# Создаем функцию, которая красиво печатает поле с названием и значением.
def print_field(label, value):
    # Печатаем название поля и его значение с отступом, чтобы список было легче читать.
    print(f"   {label}: {value}")


# Создаем функцию, которая красиво печатает пункт списка.
def print_option(option_key, option_text):
    # Печатаем номер пункта и текст с небольшим отступом слева.
    print(f"  {option_key}. {option_text}")


# Создаем функцию, которая спрашивает пункт меню, пока игрок не введет правильный вариант.
def ask_option(options, prompt, error_message):
    # Запускаем бесконечный цикл, чтобы повторять вопрос при неправильном вводе.
    while True:
        # Спрашиваем ответ у игрока и убираем лишние пробелы по краям.
        answer = input(add_exit_text_to_prompt(prompt)).strip()
        # Проверяем, не хочет ли игрок выйти из игры.
        check_exit_command(answer)
        # Проверяем, есть ли такой ответ среди разрешенных вариантов.
        if answer in options:
            # Возвращаем правильный ответ, чтобы игра пошла дальше.
            return answer
        # Сообщаем игроку, что такого варианта нет.
        print(error_message)


# Создаем функцию, которая спрашивает номер из списка, пока игрок не введет правильное число.
def ask_number(max_number, prompt):
    # Запускаем бесконечный цикл, чтобы повторять вопрос при неправильном вводе.
    while True:
        # Спрашиваем ответ у игрока и убираем лишние пробелы по краям.
        answer = input(add_exit_text_to_prompt(prompt)).strip()
        # Проверяем, не хочет ли игрок выйти из игры.
        check_exit_command(answer)
        # Пробуем превратить ответ игрока в число.
        try:
            # Превращаем номер человека в индекс списка, потому что списки в Python начинаются с нуля.
            index = int(answer) - 1
        # Ловим ошибку, если игрок написал не число.
        except ValueError:
            # Просим игрока ввести именно число.
            print("Ошибка! Введите число.")
            # Возвращаемся к началу цикла и спрашиваем снова.
            continue
        # Проверяем, что индекс попал внутрь списка.
        if 0 <= index < max_number:
            # Возвращаем правильный индекс.
            return index
        # Сообщаем игроку, что такого номера нет.
        print("Неверный номер!")


# Создаем функцию, которая спрашивает обычный текст и тоже разрешает выйти через 0.
def ask_text(prompt):
    # Спрашиваем текст у игрока и убираем лишние пробелы по краям.
    answer = input(add_exit_text_to_prompt(prompt)).strip()
    # Проверяем, не хочет ли игрок выйти из игры.
    check_exit_command(answer)
    # Возвращаем введенный текст.
    return answer


# Создаем функцию, которая ждет, пока игрок нажмет Enter.
def wait_for_enter():
    # Показываем игроку подсказку и сохраняем его ответ.
    answer = input("\nНажми Enter, чтобы продолжить, или введи 0, чтобы выйти из игры: ").strip()
    # Проверяем, хочет ли игрок выйти из игры.
    check_exit_command(answer)
