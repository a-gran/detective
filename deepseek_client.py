# Этот файл отвечает за разговор игры с нейросетью Groq.
# Его можно представить как телефон: игра набирает номер сервера, отправляет вопрос и ждет ответ.
# Здесь нет логики выбора подозреваемого или вопроса, потому что этим занимается interview.py.
# В этом файле мы только собираем понятную инструкцию для AI и отправляем ее в интернет.

# Берем переменные окружения, чтобы читать API-ключ.
# Переменные окружения похожи на тайный ящик компьютера.
# В этот ящик можно положить секретный ключ и не писать его прямо в коде.
import os

# Берем библиотеку для HTTP-запросов к Groq.
# HTTP-запрос - это сообщение, которое программа отправляет серверу через интернет.
# Библиотека requests помогает отправить такое сообщение короткой командой.
import requests


# Создаем функцию, которая отправляет запрос в Groq.
# Функция получает prompt - большой текст с правилами для нейросети.
# Внутри prompt написано, кем должна притвориться нейросеть и на какой вопрос ответить.
def ask_groq(prompt):
    # Берем ключ из переменной окружения.
    # Ключ называется GROQ_API_KEY, потому что именно такое имя мы договорились использовать в проекте.
    # os.getenv пытается найти этот ключ среди переменных окружения компьютера.
    api_key = os.getenv("GROQ_API_KEY")

    # Проверяем, что ключ задан.
    # Если ключа нет, переменная api_key будет пустой.
    # Без ключа Groq не поймет, кому разрешить доступ к нейросети.
    if not api_key:
        # Поднимаем ошибку, чтобы сразу было видно, что AI-клиент не подключен.
        # raise означает: "останови обычное выполнение и сообщи о проблеме".
        # Так ошибку можно поймать выше и показать человеку понятное объяснение.
        raise ValueError("Groq не подключен. Проверь переменную GROQ_API_KEY.")

    # Отправляем запрос в Groq.
    # requests.post отправляет данные на сервер.
    # POST используют, когда мы не просто открываем страницу, а передаем серверу информацию.
    response = requests.post(
        # Это адрес сервера Groq, который принимает запросы в формате OpenAI Chat Completions.
        "https://api.groq.com/openai/v1/chat/completions",

        # headers - это служебные подписи к запросу.
        # По ним сервер понимает, кто отправляет запрос и какой формат данных внутри.
        headers={
            # Authorization передает секретный ключ.
            # Bearer означает, что мы показываем серверу специальный токен доступа.
            "Authorization": f"Bearer {api_key}",
            # Content-Type говорит серверу: "Мы отправляем данные в формате JSON".
            "Content-Type": "application/json",
        },

        # json - это тело запроса.
        # Здесь лежит главное задание для нейросети.
        json={
            # model говорит Groq, какую именно AI-модель нужно запустить.
            "model": "openai/gpt-oss-20b",

            # messages - это список сообщений для модели.
            # Модель читает их сверху вниз, как переписку в чате.
            "messages": [
                # system-сообщение задает общую роль модели.
                # Здесь мы говорим: "Ты не обычный помощник, ты персонаж детективной игры".
                {"role": "system", "content": "Ты персонаж детективной игры. Отвечай на русском языку."},
                # user-сообщение передает подробный prompt.
                # В нем есть имя героя, его алиби, секрет, дело и вопрос игрока.
                {"role": "user", "content": prompt},
            ],

            # temperature управляет свободой ответа.
            # Маленькое число делает ответ спокойнее и предсказуемее.
            # Большое число делает ответ более творческим, но иногда менее точным.
            "temperature": 0.9,
        },

        # timeout ограничивает время ожидания ответа.
        # Если сервер долго молчит, программа не будет ждать бесконечно.
        timeout=500,
    )

    # Проверяем код ответа от сервера.
    # Если сервер ответил ошибкой, например из-за неправильного ключа, эта строка создаст исключение.
    # Исключение помогает понять, что запрос не удался.
    response.raise_for_status()

    # Возвращаем текст ответа модели.
    # response.json() превращает ответ сервера из JSON в словарь Python.
    # choices[0]["message"]["content"] - это место, где лежит готовый текст нейросети.
    # Игре не нужны все технические данные, ей нужен только сам ответ персонажа.
    return response.json()["choices"][0]["message"]["content"]


# Создаем функцию, которая собирает учебный промпт для ответа персонажа.
# Эта функция ничего не отправляет в интернет.
# Она просто делает большую строку, которую потом можно отправить в ask_groq().
# Хороший prompt похож на четкое задание: кто ты, что известно и какие правила нельзя нарушать.
def build_character_prompt(suspect, question_text, case_data):
    # Возвращаем текст промпта, который позже можно отправить в AI-модель.
    # Скобки после return позволяют собрать одну длинную строку из многих маленьких кусочков.
    return (
        # Добавляем роль модели в игре.
        # Так AI понимает, что должен отвечать от лица подозреваемого, а не как учитель.
        "Ты играешь роль подозреваемого в детективной игре.\n\n"

        # Добавляем имя подозреваемого.
        # Имя нужно, чтобы модель знала, какого персонажа она играет.
        f"Имя: {suspect['name']}.\n"

        # Добавляем роль подозреваемого.
        # Роль помогает отвечать в контексте истории: дочь, партнер, дворецкий и так далее.
        f"Роль: {suspect['role']}.\n"

        # Добавляем характер подозреваемого.
        # Характер помогает сделать ответ живым, а не одинаковым для всех персонажей.
        f"Характер: {suspect['personality']}.\n"

        # Добавляем алиби подозреваемого.
        # Алиби - это версия персонажа о том, где он был во время преступления.
        f"Алиби: {suspect['alibi']}.\n"

        # Добавляем секрет подозреваемого.
        # Секрет нужен, чтобы модель понимала скрытую правду персонажа.
        # Но правила ниже запрещают раскрывать всю развязку слишком рано.
        f"Секрет: {suspect['secret']}.\n\n"

        # Добавляем название дела.
        # Название помогает модели не забыть, в какой истории происходит разговор.
        f"Дело: {case_data['title']}.\n"

        # Добавляем описание дела.
        # Описание дела - это главные факты расследования.
        # Модель должна опираться на них, а не придумывать новую историю.
        f"Описание дела: {case_data['description']}\n\n"

        # Добавляем правила безопасности для модели.
        # Правила нужны, чтобы нейросеть не испортила игру случайной выдумкой.
        "Правила:\n"

        # Запрещаем модели придумывать новые факты.
        # Если AI добавит новую улику, игроку станет нечестно расследовать дело.
        "- Не придумывай новые факты.\n"

        # Запрещаем модели менять преступника.
        # Преступник уже записан в данных игры, и модель не должна менять решение.
        "- Не меняй преступника.\n"

        # Запрещаем модели раскрывать ответ слишком рано.
        # Во время допроса персонаж может намекать, но не должен сразу назвать виновного.
        "- Не раскрывай преступника прямо во время допроса.\n"

        # Просим отвечать коротко.
        # Короткий ответ удобнее читать в консольной игре.
        "- Отвечай коротко, 1-3 предложения.\n\n"

        # Добавляем вопрос игрока.
        # Это конкретный вопрос, который выбрал игрок в меню допроса.
        f"Вопрос игрока: {question_text}"
    )


# Создаем функцию, которая получает ответ персонажа через Groq.
# Это главная функция для допроса.
# Ее вызывает interview.py, когда игрок уже выбрал подозреваемого и вопрос.
def get_character_answer(suspect, question_key, question_text, case_data):
    # Собираем промпт для модели.
    # Передаем в prompt данные подозреваемого, текст вопроса и описание дела.
    prompt = build_character_prompt(suspect, question_text, case_data)

    # Пробуем отправить промпт в Groq и получить ответ.
    try:
        # Вызываем нейросеть и сохраняем ее ответ в переменную answer.
        answer = ask_groq(prompt)
    # Ловим любую ошибку, если нейросеть, интернет или API не ответили нормально.
    except Exception:
        # Возвращаем понятный текст для игрока вместо красной ошибки в консоли.
        return "Не отвечает нейросеть"

    # Возвращаем ответ модели и промпт для учебного разбора.
    # answer - то, что увидит игрок.
    # prompt - то, что можно показать ученикам, чтобы разобрать, как был составлен запрос.
    return answer

    # Запасной режим отключен, чтобы ответы шли только через AI-агента.
    # Следующая строка специально оставлена как комментарий.
    # Комментарий Python не выполняет, поэтому эта строка не может сама вернуть ответ.
    # Если Groq не работает, можно временно вернуть эту строку:
    # return suspect["answers"][question_key], prompt


# Создаем функцию, которая просит AI красиво переформулировать выбранную кодом подсказку.
# Код игры сам выбирает подсказку, а AI только делает ее более красивой по тексту.
# Так модель не придумывает новую подсказку и не раскрывает лишнего.
def rewrite_hint_with_ai(current_hint, game_state, case_data):
    # Собираем промпт, в котором AI получает только уже выбранную подсказку и состояние игры.
    # current_hint - это подсказка, которую уже выбрал обычный код.
    # game_state - это состояние игры: что игрок уже видел и сколько действий осталось.
    prompt = (
        # Объясняем модели ее роль в игре.
        # Здесь AI не подозреваемый, а помощник детектива.
        "Ты помощник в детективной игре.\n\n"

        # Передаем название дела, чтобы ответ был в теме расследования.
        f"Дело: {case_data['title']}.\n"

        # Передаем описание дела, чтобы модель не уходила в другую историю.
        f"Описание дела: {case_data['description']}\n\n"

        # Передаем подсказку, которую уже выбрал код игры.
        # AI должен менять только форму текста, а не смысл.
        f"Подсказка, выбранная кодом: {current_hint}\n"

        # Передаем список просмотренных улик, чтобы подсказка могла звучать точнее.
        f"Уже просмотренные улики: {game_state['viewed_clues']}\n"

        # Передаем количество оставшихся вопросов.
        # Это помогает модели понять, насколько осторожной должна быть подсказка.
        f"Осталось вопросов: {game_state['questions_left']}\n"

        # Передаем количество оставшихся подсказок.
        # Это тоже часть текущего состояния игры.
        f"Осталось подсказок: {game_state['hints_left']}\n\n"

        # Открываем блок правил для AI.
        # Эти правила удерживают ответ в рамках уже написанной игры.
        "Правила:\n"

        # Запрещаем менять смысл подсказки.
        # Иначе подсказка может стать другой и сломать баланс игры.
        "- Не меняй смысл подсказки.\n"

        # Запрещаем называть преступника напрямую.
        # Подсказка должна помогать думать, а не сразу завершать расследование.
        "- Не называй преступника напрямую.\n"

        # Запрещаем добавлять новые факты.
        # В игре должны использоваться только те факты, которые уже есть в data.py.
        "- Не добавляй новые факты, улики, людей или места.\n"

        # Просим сделать текст атмосфернее.
        # Это делает подсказку приятнее для чтения, но смысл должен остаться тем же.
        "- Переформулируй подсказку атмосферно и понятно.\n"

        # Ограничиваем длину ответа.
        # Короткая подсказка не перегружает игрока.
        "- Ответь 1-2 предложениями."
    )

    # Отправляем промпт в Groq и возвращаем переформулированную подсказку.
    # Здесь используется та же функция ask_groq(), что и для допроса.
    return ask_groq(prompt)


# Создаем функцию, которая просит AI кратко пересказать историю допросов.
# Эта функция полезна, когда игрок уже задал несколько вопросов и хочет вспомнить главное.
def summarize_history_with_ai(game_state, case_data):
    # Собираем промпт с историей допросов и правилами безопасности.
    # В prompt попадут только уже проведенные допросы из game_state.
    prompt = (
        # Объясняем модели, что нужно сделать краткую сводку.
        # Здесь AI играет роль помощника детектива, который делает заметки.
        "Ты помощник детектива и кратко подводишь итоги допросов.\n\n"

        # Передаем название дела.
        f"Дело: {case_data['title']}.\n"

        # Передаем описание дела.
        f"Описание дела: {case_data['description']}\n\n"

        # Передаем историю допросов из состояния игры.
        # Это список вопросов и ответов, которые игрок уже получил.
        f"История допросов: {game_state['question_history']}\n\n"

        # Открываем блок правил.
        # Правила не дают модели превратить краткую сводку в новую историю.
        "Правила:\n"

        # Запрещаем добавлять новые факты.
        # Сводка должна пересказывать только то, что уже было в истории.
        "- Не добавляй новые факты, улики, людей или места.\n"

        # Запрещаем делать вывод о преступнике как окончательный.
        # До финального обвинения игра не должна выдавать готовый ответ.
        "- Не называй преступника как доказанный факт.\n"

        # Просим опираться только на историю.
        # Это защищает игру от случайных догадок модели.
        "- Опирайся только на историю допросов выше.\n"

        # Просим короткий формат.
        # Игроку нужна быстрая памятка, а не длинный пересказ.
        "- Ответь 2-4 короткими предложениями."
    )

    # Отправляем промпт в Groq и возвращаем краткое резюме.
    # Если запрос пройдет успешно, функция вернет текст модели.
    return ask_groq(prompt)


# Создаем функцию, которая учебно анализирует финальную версию игрока.
# Эта функция нужна в конце игры, когда игрок выбрал подозреваемого и написал свою версию.
def analyze_player_version(player_version, accused_name, case_data):
    # Проверяем, выбрал ли игрок правильного преступника.
    # lower() делает обе строки маленькими буквами.
    # Так сравнение не сломается, если где-то случайно поменялся регистр букв.
    is_correct = accused_name.lower() == case_data["criminal"].lower()

    # Собираем промпт, где код уже передал правильность выбора.
    # Важно: правильность считает обычный Python-код, а не нейросеть.
    # Нейросеть только красиво объясняет результат.
    prompt = (
        # Объясняем модели роль проверяющего помощника.
        # Здесь AI говорит как мягкий наставник, а не как подозреваемый.
        "Ты помощник преподавателя на детективной игре по Python.\n\n"

        # Передаем название дела.
        f"Дело: {case_data['title']}.\n"

        # Передаем правильного преступника из кода.
        # Это нужно, чтобы AI не придумал другого виновного.
        f"Правильный преступник: {case_data['criminal']}.\n"

        # Передаем правильное решение из кода.
        # По нему AI понимает, какие аргументы должны быть в хорошем объяснении.
        f"Правильное решение: {case_data['solution']}\n\n"

        # Передаем подозреваемого, которого выбрал игрок.
        f"Игрок обвинил: {accused_name}.\n"

        # Передаем версию игрока.
        # Это текст, где игрок объясняет свою логику.
        f"Версия игрока: {player_version}\n"

        # Передаем результат проверки, который посчитал код.
        # Модель должна принять этот результат и не спорить с ним.
        f"Код уже проверил выбор. Выбор правильный: {is_correct}.\n\n"

        # Открываем блок правил для модели.
        # Правила помогают получить честный и полезный комментарий.
        "Правила:\n"

        # Запрещаем менять результат проверки.
        # Если код решил, что ответ правильный или неправильный, AI обязан это сохранить.
        "- Не меняй результат проверки кода.\n"

        # Запрещаем менять преступника.
        # Преступник хранится в CASE_DATA и является частью правил игры.
        "- Не меняй преступника.\n"

        # Запрещаем добавлять новые факты.
        # В комментарии нельзя появляться уликам, которых не было в проекте.
        "- Не добавляй новые факты, улики, людей или места.\n"

        # Просим мягкую оценку.
        # Игрок должен получить поддержку и понятную обратную связь.
        "- Мягко оцени версию игрока.\n"

        # Просим сказать, что получилось хорошо.
        # Это помогает ученику увидеть сильные места своей логики.
        "- Скажи, какие аргументы выглядят сильными.\n"

        # Просим сказать, чего не хватает.
        # Это помогает ученику понять, как улучшить объяснение.
        "- Скажи, чего не хватает в объяснении.\n"

        # Ограничиваем длину ответа.
        # Финальный комментарий должен быть коротким и понятным.
        "- Ответь 2-4 короткими предложениями."
    )

    # Отправляем промпт в Groq и возвращаем AI-комментарий.
    # Добавляем подпись "Комментарий помощника", чтобы игрок понял, кто говорит.
    return "\nКомментарий помощника: " + ask_groq(prompt)
