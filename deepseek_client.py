# Подключаем модуль os.
# Он нужен, чтобы читать переменные окружения.
# Переменные окружения помогают хранить секретные данные не прямо в коде.
# В этом проекте через os мы берем API-ключ для Groq.
import os
# Подключаем библиотеку requests.
# Она умеет отправлять HTTP-запросы в интернет.
# Здесь она нужна, чтобы отправить промпт в Groq и получить ответ AI-модели.
import requests


# Создаем функцию, которая отправляет один запрос в Groq.
# На вход функция получает prompt.
# Prompt - это текстовая инструкция для AI-модели.
# В prompt мы объясняем модели, какую роль она играет и что должна ответить.
def ask_groq(prompt):
    # Берем API-ключ из переменной окружения GROQ_API_KEY.
    # API-ключ похож на пароль для доступа к сервису Groq.
    # Его нельзя писать прямо в коде, потому что код могут увидеть другие люди.
    api_key = os.getenv("GROQ_API_KEY")
    # Проверяем, получилось ли найти ключ.
    # Если ключа нет, запрос в Groq все равно не сможет выполниться.
    if not api_key:
        # Поднимаем понятную ошибку.
        # Позже другая функция поймает эту ошибку и возьмет готовый ответ из data.py.
        # Благодаря этому игра не сломается полностью, если AI не подключен.
        raise ValueError("Groq не подключен. Проверь переменную GROQ_API_KEY.")
    # Отправляем POST-запрос в Groq.
    # POST-запрос нужен, когда мы передаем серверу данные и ждем ответ.
    response = requests.post(
        # Указываем адрес Groq API, куда отправляется запрос.
        "https://api.groq.com/openai/v1/chat/completions",
        # Передаем заголовки запроса.
        # Заголовки помогают серверу понять, кто отправил запрос и в каком формате данные.
        headers={
            # Передаем API-ключ в заголовке Authorization.
            # Слово Bearer означает, что мы предъявляем токен доступа.
            "Authorization": f"Bearer {api_key}",
            # Сообщаем серверу, что отправляем данные в формате JSON.
            "Content-Type": "application/json",
        },
        # Передаем тело запроса.
        # Здесь описано, какую модель вызвать и какие сообщения ей отправить.
        json={
            # Выбираем модель Groq.
            # От модели зависит качество, скорость и стиль ответа.
            "model": "openai/gpt-oss-20b",
            # Передаем список сообщений для модели.
            # Модель читает эти сообщения и по ним составляет ответ.
            "messages": [
                # System-сообщение задает общую роль модели.
                # Оно говорит модели: "Сейчас ты персонаж детективной игры".
                {"role": "system", "content": "Ты персонаж детективной игры. Всегда отвечай только на русском языке."},
                # User-сообщение содержит подробный промпт.
                # В нем есть данные подозреваемого, описание дела, правила и вопрос игрока.
                {"role": "user", "content": prompt},
            ],
            # Temperature отвечает за разнообразие ответа.
            # Чем значение выше, тем свободнее и непредсказуемее ответы.
            # Здесь значение небольшое, чтобы персонаж отвечал живо, но не слишком фантазировал.
            "temperature": 0.9,
        },
        # timeout ограничивает время ожидания ответа.
        # Если сервер долго не отвечает, программа не будет зависать бесконечно.
        timeout=500,
    )
    # Проверяем, не вернул ли сервер ошибку.
    # Например, ошибка может быть из-за неправильного ключа или проблем с интернетом.
    # Если ошибка есть, requests поднимет исключение.
    response.raise_for_status()
    # Превращаем ответ сервера из JSON в обычный словарь Python.
    # Затем достаем из него текст, который написала модель.
    # Возвращаем только текст ответа, потому что игре не нужны технические данные ответа.
    return response.json()["choices"][0]["message"]["content"]


# Создаем функцию, которая собирает промпт для ответа персонажа.
# Эта функция ничего не отправляет в интернет.
# Она только готовит большой текст с инструкциями для AI.
def build_character_prompt(suspect, question_text, case_data):
    # Возвращаем один длинный текст.
    # В этот текст складываем данные подозреваемого, данные дела и правила поведения AI.
    return (
        # Объясняем AI, что он должен играть роль подозреваемого, а не помощника игрока.
        "Ты играешь роль подозреваемого в детективной игре.\n\n"
        # Передаем имя выбранного подозреваемого.
        # Так AI понимает, от чьего лица нужно отвечать.
        f"Имя: {suspect['name']}.\n"
        # Передаем роль подозреваемого.
        # Например, это может быть дворецкий, наследник, секретарь или другой персонаж.
        f"Роль: {suspect['role']}.\n"
        # Передаем характер подозреваемого.
        # Это помогает AI отвечать не сухо, а в стиле персонажа.
        f"Характер: {suspect['personality']}.\n"
        # Передаем алиби подозреваемого.
        # AI должен учитывать алиби и не придумывать новое.
        f"Алиби: {suspect['alibi']}.\n"
        # Передаем секрет подозреваемого.
        # Секрет помогает сделать ответ интереснее, но AI не должен раскрывать все слишком рано.
        f"Секрет: {suspect['secret']}.\n\n"
        # Передаем название дела.
        # Это помогает AI понимать общий контекст расследования.
        f"Дело: {case_data['title']}.\n"
        # Передаем описание дела.
        # AI должен опираться только на это описание и данные из проекта.
        f"Описание дела: {case_data['description']}\n\n"
        # Добавляем правила для AI.
        # Эти правила нужны, чтобы модель не ломала игру и не придумывала лишнее.
        "Правила:\n"
        # Запрещаем придумывать новые факты.
        # Если AI начнет добавлять новые улики или события, игроку будет нечестно расследовать дело.
        "- Не придумывай новые факты.\n"
        # Запрещаем менять преступника.
        # Настоящий преступник уже записан в data.py, и AI не должен менять правила игры.
        "- Не меняй преступника.\n"
        # Запрещаем раскрывать преступника прямо во время допроса.
        # Иначе игра закончится слишком быстро и расследование потеряет смысл.
        "- Не раскрывай преступника прямо во время допроса.\n"
        # Просим отвечать коротко.
        # Короткий ответ удобнее читать в консольной игре.
        "- Отвечай коротко, 1-3 предложения.\n\n"
        # Передаем вопрос, который выбрал игрок.
        # AI должен отвечать именно на этот вопрос.
        f"Вопрос игрока: {question_text}"
    )


# Создаем функцию, которая получает ответ персонажа.
# Эта функция связывает игру и AI-клиент.
# Именно ее вызывает interview.py во время допроса.
def get_character_answer(suspect, question_key, question_text, case_data):
    # Сначала собираем промпт.
    # Без промпта AI не будет знать, кто он, что случилось и как отвечать.
    prompt = build_character_prompt(suspect, question_text, case_data)
    # Пробуем получить живой ответ из Groq.
    # Слово try означает: "попробуй выполнить этот код, но будь готов к ошибке".
    try:
        # Отправляем промпт в Groq и получаем ответ модели.
        answer = ask_groq(prompt)
        # Возвращаем ответ модели в interview.py.
        # Игрок увидит именно этот текст во время допроса.
        return answer
    except (ValueError, requests.RequestException):
        # Если ключа нет или запрос к Groq не получился, берем готовый ответ из data.py.
        # Это запасной вариант, чтобы игра все равно работала без интернета или без API-ключа.
        # Мы ловим только ожидаемые ошибки AI-запроса.
        # Ошибки в данных лучше не прятать, чтобы их можно было заметить и исправить.
        # return suspect["answers"][question_key]
        return "Ответа от нейросети нет"


# Создаем функцию, которая учебно анализирует финальную версию игрока.
# Сейчас здесь используется простой готовый текст, а не запрос к AI.
# Так финал работает стабильно даже без подключения к Groq.
def analyze_player_version(player_version, accused_name, case_data):
    # Проверяем, выбрал ли игрок правильного преступника.
    print(f'Версия детектива: {player_version}')
    # lower() делает строки маленькими буквами, чтобы сравнение было мягче к регистру.
    is_correct = accused_name.lower() == case_data["criminal"].lower()
    # Если игрок выбрал верно, возвращаем дружелюбный комментарий.
    if is_correct:
        # Возвращаем короткий учебный анализ для правильного ответа.
        # Он напоминает, что важно не только назвать преступника, но и объяснить версию уликами.
        return (
            "\nКомментарий помощника: версия выбрана правильно. "
            "Теперь важно объяснить ее уликами: журналом пропусков, следами на клавиатуре и флешкой."
        )
    # Если игрок выбрал неверно, возвращаем подсказку для размышления.
    # Комментарий не раскрывает весь ответ заново, а советует сравнить алиби и улики.
    return (
        "\nКомментарий помощника: выбран не тот подозреваемый. "
        "Стоит еще раз сравнить алиби, улики и предметы, на которых мог быть файл."
    )
