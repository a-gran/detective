# Создаем функцию, которая просит выбрать сложность.
def choose_difficulty():
    # Запускаем бесконечный цикл, пока игрок не выберет правильный пункт.
    while True:
        # Печатаем заголовок выбора сложности.
        print("\nВыбор сложности")
        # Печатаем разделитель.
        print_separator()
        # Показываем легкий режим.
        print("1. Легкий: 8 вопросов, 3 подсказки")
        # Показываем средний режим.
        print("2. Средний: 6 вопросов, 2 подсказки")
        # Показываем сложный режим.
        print("3. Сложный: 4 вопроса, 1 подсказка")
        # Получаем выбор игрока.
        choice = input("Выбери сложность: ").strip()
        # Проверяем, есть ли такой выбор в словаре сложностей.
        if choice in DIFFICULTY_SETTINGS:
            # Возвращаем выбранные настройки сложности.
            return DIFFICULTY_SETTINGS[choice]
        # Сообщаем, что игрок ввел неправильный пункт.
        print("Такого варианта нет. Попробуй еще раз.")


# Создаем функцию, которая делает новое состояние игры.
def create_game_state(difficulty):
    # Возвращаем словарь с текущими данными игрока.
    return {
        # Сохраняем выбранную сложность.
        "difficulty": difficulty["name"],
        # Сохраняем количество оставшихся вопросов.
        "questions_left": difficulty["questions"],
        # Сохраняем количество оставшихся подсказок.
        "hints_left": difficulty["hints"],
        # Создаем список изученных улик.
        "viewed_clues": [],
        # Создаем список истории допросов.
        "question_history": [],
    }


