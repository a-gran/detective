# Создаем функцию, которая показывает улики.
def show_clues(game_state):
    # Печатаем заголовок улик.
    print("\nУлики")
    # Печатаем разделитель.
    print_separator()
    # Перебираем все улики вместе с номером.
    for index, clue in enumerate(CLUES, start=1):
        # Печатаем название улики.
        print(f"{index}. {clue['title']}")
        # Печатаем описание улики.
        print(f"   {clue['description']}")
        # Проверяем, есть ли улика в списке уже изученных.
        if clue["title"] not in game_state["viewed_clues"]:
            # Добавляем улику в список изученных.
            game_state["viewed_clues"].append(clue["title"])
    # Ждем, пока игрок прочитает улики.
    wait_for_enter()


# Создаем функцию, которая помогает выбрать подозреваемого по номеру.
def choose_suspect():
    # Показываем список подозреваемых с номерами.
    for index, suspect in enumerate(SUSPECTS, start=1):
        # Печатаем номер и имя подозреваемого.
        print(f"{index}. {suspect['name']}")
    # Получаем выбор игрока.
    choice = input("Выбери подозреваемого: ").strip()
    # Проверяем, является ли ввод числом.
    if not choice.isdigit():
        # Возвращаем пустое значение, если игрок ввел не число.
        return None
    # Превращаем выбор игрока в индекс списка.
    suspect_index = int(choice) - 1
    # Проверяем, находится ли индекс внутри списка подозреваемых.
    if 0 <= suspect_index < len(SUSPECTS):
        # Возвращаем выбранного подозреваемого.
        return SUSPECTS[suspect_index]
    # Возвращаем пустое значение, если номер неправильный.
    return None


# Создаем функцию, которая показывает вопросы для допроса.
def show_interview_questions():
    # Перебираем все вопросы вместе с их номерами.
    for question_key, question_text in INTERVIEW_QUESTIONS.items():
        # Печатаем номер и текст одного вопроса.
        print(f"{question_key}. {question_text}")


# Создаем функцию, которая превращает номер вопроса в текст вопроса.
def get_question_text(question_key):
    # Возвращаем текст вопроса по номеру.
    return INTERVIEW_QUESTIONS[question_key]


# Создаем функцию, которая проводит допрос.
def interview_suspect(game_state):
    # Проверяем, остались ли у игрока вопросы.
    if game_state["questions_left"] <= 0:
        # Сообщаем, что вопросы закончились.
        print("\nВопросы закончились. Пора делать выводы.")
        # Ждем, пока игрок прочитает сообщение.
        wait_for_enter()
        # Завершаем функцию.
        return
    # Печатаем заголовок допроса.
    print("\nДопрос")
    # Печатаем разделитель.
    print_separator()
    # Просим игрока выбрать подозреваемого.
    suspect = choose_suspect()
    # Проверяем, выбран ли подозреваемый правильно.
    if suspect is None:
        # Сообщаем об ошибке выбора.
        print("Такого подозреваемого нет.")
        # Ждем, пока игрок прочитает сообщение.
        wait_for_enter()
        # Завершаем функцию.
        return
    # Показываем вопросы.
    show_interview_questions()
    # Получаем выбранный вопрос.
    question = input("Выбери вопрос: ").strip()
    # Проверяем, есть ли такой вопрос у персонажа.
    if question not in suspect["answers"]:
        # Сообщаем, что вопрос неправильный.
        print("Такого вопроса нет.")
        # Ждем, пока игрок прочитает сообщение.
        wait_for_enter()
        # Завершаем функцию.
        return
    # Получаем текст выбранного вопроса.
    question_text = get_question_text(question)
    # Получаем ответ подозреваемого через учебную точку подключения DeepSeek.
    answer, prompt = get_character_answer(suspect, question, question_text, CASE_DATA)
    # Уменьшаем количество оставшихся вопросов.
    game_state["questions_left"] -= 1
    # Добавляем запись в историю допросов.
    game_state["question_history"].append(f"{suspect['name']}: {answer}")
    # Печатаем имя подозреваемого и ответ.
    print(f"\n{suspect['name']}: {answer}")
    # Печатаем количество оставшихся вопросов.
    print(f"Осталось вопросов: {game_state['questions_left']}")
    # Ждем, пока игрок прочитает ответ.
    wait_for_enter()


# Создаем функцию, которая показывает подсказку.
def show_hint(game_state):
    # Проверяем, остались ли подсказки.
    if game_state["hints_left"] <= 0:
        # Сообщаем, что подсказки закончились.
        print("\nПодсказки закончились.")
        # Ждем, пока игрок прочитает сообщение.
        wait_for_enter()
        # Завершаем функцию.
        return
    # Вычисляем номер подсказки по количеству уже использованных подсказок.
    hint_index = len(HINTS) - game_state["hints_left"]
    # Проверяем, не вышел ли номер за пределы списка.
    if hint_index >= len(HINTS):
        # Используем последнюю подсказку, если список закончился.
        hint_index = len(HINTS) - 1
    # Уменьшаем количество подсказок.
    game_state["hints_left"] -= 1
    # Печатаем подсказку.
    print(f"\nПодсказка: {HINTS[hint_index]}")
    # Печатаем количество оставшихся подсказок.
    print(f"Осталось подсказок: {game_state['hints_left']}")
    # Ждем, пока игрок прочитает подсказку.
    wait_for_enter()


# Создаем функцию, которая показывает историю допросов.
def show_history(game_state):
    # Печатаем заголовок истории.
    print("\nИстория допросов")
    # Печатаем разделитель.
    print_separator()
    # Проверяем, есть ли история.
    if not game_state["question_history"]:
        # Сообщаем, что вопросов еще не было.
        print("Ты еще никого не допрашивал.")
    # Если история есть, показываем ее.
    else:
        # Перебираем все записи истории.
        for record in game_state["question_history"]:
            # Печатаем одну запись истории.
            print(f"- {record}")
    # Ждем, пока игрок прочитает историю.
    wait_for_enter()


# Создаем функцию, которая проводит финальное обвинение.
def make_accusation():
    # Печатаем заголовок финала.
    print("\nФинальное обвинение")
    # Печатаем разделитель.
    print_separator()
    # Просим игрока выбрать подозреваемого.
    suspect = choose_suspect()
    # Проверяем, выбран ли подозреваемый правильно.
    if suspect is None:
        # Сообщаем об ошибке выбора.
        print("Такого подозреваемого нет.")
        # Ждем, пока игрок прочитает сообщение.
        wait_for_enter()
        # Возвращаем значение, что игра не завершилась.
        return False
    # Просим игрока объяснить версию.
    version = input("Объясни свою версию: ").strip()
    # Печатаем разделитель.
    print_separator()
    # Проверяем, совпадает ли имя выбранного подозреваемого с преступником.
    if suspect["name"].lower() == CASE_DATA["criminal"].lower():
        # Поздравляем игрока с победой.
        print("Верно! Ты нашел преступника.")
    # Если игрок ошибся, показываем мягкое сообщение.
    else:
        # Сообщаем, что выбран неверный подозреваемый.
        print("Ответ неверный. Но расследование все равно помогло найти правду.")
    # Показываем версию игрока.
    print(f"\nТвоя версия: {version}")
    # Показываем правильное объяснение.
    print(f"\nПравильное объяснение: {CASE_DATA['solution']}")
    # Получаем учебный анализ версии игрока.
    assistant_comment = analyze_player_version(version, suspect["name"], CASE_DATA)
    # Показываем учебный анализ версии игрока.
    print(assistant_comment)
    # Ждем, пока игрок прочитает финал.
    wait_for_enter()
    # Возвращаем значение, что игра завершилась.
    return True


# Создаем функцию, которая показывает меню внутри расследования.
