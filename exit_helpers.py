# Создаем функцию, которая красиво завершает игру.
def exit_game():
    # Импортируем print_title здесь, чтобы избежать циклического импорта в начале файла.
    from ui_helpers import print_title

    # Печатаем красивое сообщение перед выходом.
    print_title("До встречи, детектив!")
    # Завершаем программу полностью.
    raise SystemExit


# Создаем функцию, которая проверяет, хочет ли игрок выйти из игры.
def check_exit_command(answer):
    # Проверяем, ввел ли игрок команду выхода.
    if answer == "0":
        # Завершаем игру, если игрок ввел 0.
        exit_game()


# Создаем функцию, которая добавляет к подсказке ввода информацию про выход через 0.
def add_exit_text_to_prompt(prompt):
    # Проверяем, есть ли уже в подсказке текст про 0.
    if "0" in prompt:
        # Возвращаем подсказку без изменений, если 0 уже упомянут.
        return prompt
    # Проверяем, заканчивается ли подсказка пробелом.
    if prompt.endswith(" "):
        # Добавляем текст про выход перед последним пробелом.
        return f"{prompt[:-1]} (0 - выйти): "
    # Добавляем текст про выход в конец обычной подсказки.
    return f"{prompt} (0 - выйти): "
