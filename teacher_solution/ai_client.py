# Берем переменные окружения, чтобы читать API-ключ.
import os
# Берем библиотеку для HTTP-запросов к Groq.
import requests


# Создаем функцию, которая отправляет запрос в Groq.
def ask_groq(prompt):
    # Берем ключ из переменной окружения.
    api_key = os.getenv("GROQ_API_KEY")
    # Проверяем, что ключ задан.
    if not api_key:
        # Поднимаем ошибку, чтобы сразу было видно, что AI-клиент не подключен.
        raise ValueError("Groq не подключен. Проверь переменную GROQ_API_KEY.")
    # Отправляем запрос в Groq.
    response = requests.post(
        "https://api.groq.com/openai/v1/chat/completions",
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        json={
            "model": "llama-3.3-70b-versatile",
            "messages": [
                {"role": "system", "content": "Ты персонаж детективной игры."},
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.4,
        },
        timeout=30,
    )
    # Проверяем код ответа от сервера.
    response.raise_for_status()
    # Возвращаем текст ответа модели.
    return response.json()["choices"][0]["message"]["content"]


# Создаем функцию, которая собирает учебный промпт для ответа персонажа.
def build_character_prompt(suspect, question_text, case_data):
    # Возвращаем текст промпта, который позже можно отправить в AI-модель.
    return (
        # Добавляем роль модели в игре.
        "Ты играешь роль подозреваемого в детективной игре.\n\n"
        # Добавляем имя подозреваемого.
        f"Имя: {suspect['name']}.\n"
        # Добавляем роль подозреваемого.
        f"Роль: {suspect['role']}.\n"
        # Добавляем характер подозреваемого.
        f"Характер: {suspect['personality']}.\n"
        # Добавляем алиби подозреваемого.
        f"Алиби: {suspect['alibi']}.\n"
        # Добавляем секрет подозреваемого.
        f"Секрет: {suspect['secret']}.\n\n"
        # Добавляем название дела.
        f"Дело: {case_data['title']}.\n"
        # Добавляем описание дела.
        f"Описание дела: {case_data['description']}\n\n"
        # Добавляем правила безопасности для модели.
        "Правила:\n"
        # Запрещаем модели придумывать новые факты.
        "- Не придумывай новые факты.\n"
        # Запрещаем модели менять преступника.
        "- Не меняй преступника.\n"
        # Запрещаем модели раскрывать ответ слишком рано.
        "- Не раскрывай преступника прямо во время допроса.\n"
        # Просим отвечать коротко.
        "- Отвечай коротко, 1-3 предложения.\n\n"
        # Добавляем вопрос игрока.
        f"Вопрос игрока: {question_text}"
    )


# Создаем функцию, которая получает ответ персонажа через Groq.
def get_character_answer(suspect, question_key, question_text, case_data):
    # Собираем промпт для модели.
    prompt = build_character_prompt(suspect, question_text, case_data)
    # Отправляем промпт в Groq и получаем ответ.
    answer = ask_groq(prompt)
