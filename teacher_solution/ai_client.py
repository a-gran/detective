# Создаем функцию, которая просит AI красиво переформулировать выбранную кодом подсказку.
def rewrite_hint_with_ai(current_hint, game_state, case_data):
    # Собираем промпт, в котором AI получает только уже выбранную подсказку и состояние игры.
    prompt = (
        # Объясняем модели ее роль в игре.
        "Ты помощник в детективной игре.\n\n"
        # Передаем название дела, чтобы ответ был в теме расследования.
        f"Дело: {case_data['title']}.\n"
        # Передаем описание дела, чтобы модель не уходила в другую историю.
        f"Описание дела: {case_data['description']}\n\n"
        # Передаем подсказку, которую уже выбрал код игры.
        f"Подсказка, выбранная кодом: {current_hint}\n"
        # Передаем список просмотренных улик, чтобы подсказка могла звучать точнее.
        f"Уже просмотренные улики: {game_state['viewed_clues']}\n"
        # Передаем количество оставшихся вопросов.
        f"Осталось вопросов: {game_state['questions_left']}\n"
        # Передаем количество оставшихся подсказок.
        f"Осталось подсказок: {game_state['hints_left']}\n\n"
        # Открываем блок правил для AI.
        "Правила:\n"
        # Запрещаем менять смысл подсказки.
        "- Не меняй смысл подсказки.\n"
        # Запрещаем называть преступника напрямую.
        "- Не называй преступника напрямую.\n"
        # Запрещаем добавлять новые факты.
        "- Не добавляй новые факты, улики, людей или места.\n"
        # Просим сделать текст атмосфернее.
        "- Переформулируй подсказку атмосферно и понятно.\n"
        # Ограничиваем длину ответа.
        "- Ответь 1-2 предложениями."
    )
    # Отправляем промпт в Groq и возвращаем переформулированную подсказку.
    return ask_groq(prompt)


