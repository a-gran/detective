# Создаем функцию, которая запускает одну партию.
def play_game():
    # Просим игрока выбрать сложность.
    difficulty = choose_difficulty()
    # Создаем состояние новой игры.
    game_state = create_game_state(difficulty)
    # Показываем описание дела в начале партии.
    show_case_description()
    # Запускаем цикл расследования.
    while True:
        # Показываем меню расследования и получаем выбор игрока.
        choice = show_game_menu(game_state)
        # Проверяем выбор описания дела.
        if choice == "1":
            # Показываем описание дела.
            show_case_description()
        # Проверяем выбор подозреваемых.
        elif choice == "2":
            # Показываем подозреваемых.
            show_suspects()
        # Проверяем выбор улик.
        elif choice == "3":
            # Показываем улики.
            show_clues(game_state)
        # Проверяем выбор допроса.
        elif choice == "4":
            # Запускаем допрос.
            interview_suspect(game_state)
        # Проверяем выбор подсказки.
        elif choice == "5":
            # Показываем подсказку.
            show_hint(game_state)
        # Проверяем выбор истории.
        elif choice == "6":
            # Показываем историю допросов.
            show_history(game_state)
        # Проверяем выбор финального обвинения.
        elif choice == "7":
            # Запускаем финальное обвинение и узнаем, закончилась ли игра.
            is_finished = make_accusation()
            # Проверяем, нужно ли выйти из цикла расследования.
            if is_finished:
                # Выходим из цикла расследования.
                break
        # Проверяем выбор выхода в главное меню.
        elif choice == "8":
            # Выходим из цикла расследования.
            break
        # Обрабатываем неправильный выбор.
        else:
            # Сообщаем игроку, что такого пункта нет.
            print("Такого пункта нет. Попробуй еще раз.")


# Создаем главную функцию программы.
def main():
    # Запускаем главный цикл приложения.
    while True:
        # Показываем главное меню и получаем выбор.
        choice = show_main_menu()
        # Проверяем выбор новой игры.
        if choice == "1":
            # Запускаем игру.
            play_game()
        # Проверяем выбор правил.
        elif choice == "2":
            # Показываем правила.
            show_rules()
        # Проверяем выбор выхода.
        elif choice == "3":
            # Прощаемся с игроком.
            print("До встречи, детектив!")
            # Выходим из главного цикла.
            break
        # Обрабатываем неправильный выбор.
        else:
            # Сообщаем, что такого пункта нет.
            print("Такого пункта нет. Попробуй еще раз.")


# Проверяем, что файл запущен напрямую, а не импортирован.
if __name__ == "__main__":
    # Запускаем главную функцию программы.
    main()
