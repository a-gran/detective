# Берем список подозреваемых из файла данных.
from data import SUSPECTS

# Берем общие функции для ввода, красивого вывода подозреваемых и ожидания Enter.
from ui_helpers import ask_number, print_field, print_option, print_title, wait_for_enter


# Создайте функцию, которая показывает подозреваемых.
def show_suspects():
    # Нужно вывести заголовок "Подозреваемые".
    # Нужно вывести разделитель через print_separator().
    # Нужно пройти циклом по SUSPECTS.
    # Для каждого подозреваемого нужно вывести номер, имя, роль, характер и алиби.
    # Нужно вызвать wait_for_enter(), чтобы игрок успел прочитать список.
    # Печатаем красивый заголовок раздела подозреваемых.
    print_title("Подозреваемые")
    for i, clue in enumerate(SUSPECTS, 1):
        # Печатаем имя подозреваемого как пункт списка.
        print_option(i, clue["name"])
        # Печатаем роль подозреваемого отдельным полем.
        print_field("Роль", clue["role"])
        # Печатаем характер подозреваемого отдельным полем.
        print_field("Характер", clue["personality"])
        # Печатаем алиби подозреваемого отдельным полем.
        print_field("Алиби", clue["alibi"])
        # Добавляем пустую строку между подозреваемыми.
        print()
    # Пустую строку перед подсказкой Enter добавляет wait_for_enter().
    wait_for_enter()


# Создайте функцию, которая помогает выбрать подозреваемого.
def choose_suspect():
    # Нужно показать список подозреваемых с номерами.
    # Нужно получить выбор игрока через input().
    # Нужно проверить, что игрок ввел число.
    # Нужно превратить номер в индекс списка.
    # Если индекс правильный, нужно вернуть выбранного подозреваемого.
    # Если выбор неправильный, нужно вернуть None.
    for i, clue in enumerate(SUSPECTS, 1):
        # Печатаем имя подозреваемого как пункт выбора.
        print_option(i, clue["name"])
    index = ask_number(len(SUSPECTS), "\nКто из них подозреваемый? ")
    return SUSPECTS[index]
