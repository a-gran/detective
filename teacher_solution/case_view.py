# Берем данные дела из файла данных.
from data import CASE_DATA


# Создаем локальную функцию, которая печатает линию-разделитель.
def print_separator():
    # Печатаем строку из 60 символов "-".
    print("-" * 60)


# Создаем локальную функцию, которая ждет нажатия Enter.
def wait_for_enter():
    # Просим игрока нажать Enter, чтобы он успел прочитать текст.
    input("\nНажми Enter, чтобы продолжить...")


# Создаем функцию, которая показывает описание дела.
def show_case_description():
    # Печатаем название дела.
    print(f"\nДело: {CASE_DATA['title']}")
    # Печатаем разделитель.
    print_separator()
    # Печатаем описание дела.
    print(CASE_DATA["description"])
    # Ждем, пока игрок прочитает дело.
    wait_for_enter()


# Проверяем, что файл запущен напрямую.
if __name__ == "__main__":
    # Печатаем название проверки.
    print("Проверка файла case_view.py")
    # Показываем описание дела.
    show_case_description()
