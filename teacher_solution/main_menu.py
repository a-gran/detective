# Берем название игры из файла данных.
from data import GAME_TITLE
# Берем пункты главного меню из файла данных.
from data import MAIN_MENU_ITEMS
# Берем правила игры из файла данных.
from data import RULES_TEXT


# Создаем функцию, которая печатает линию-разделитель.
def print_separator():
    # Печатаем строку из 60 символов "-".
    print("-" * 60)


# Создаем функцию, которая ждет нажатия Enter.
def wait_for_enter():
    # Просим игрока нажать Enter, чтобы он успел прочитать текст.
    input("\nНажми Enter, чтобы продолжить...")


# Создаем функцию, которая показывает правила игры.
def show_rules():
    # Печатаем заголовок правил.
    print("\nПравила игры")
    # Печатаем разделитель.
    print_separator()
    # Перебираем все строки правил.
    for rule_line in RULES_TEXT:
        # Печатаем одну строку правил.
        print(rule_line)
    # Ждем, пока игрок прочитает правила.
    wait_for_enter()


# Создаем функцию, которая показывает главное меню.
def show_main_menu():
    # Печатаем пустую строку и название игры.
    print(f"\n{GAME_TITLE}")
    # Печатаем разделитель.
    print_separator()
    # Перебираем пункты главного меню.
    for menu_key, menu_text in MAIN_MENU_ITEMS.items():
        # Печатаем номер и название пункта.
        print(f"{menu_key}. {menu_text}")
    # Получаем выбор игрока и возвращаем его.
    return input("Выбери пункт: ").strip()


# Проверяем, что файл запущен напрямую.
if __name__ == "__main__":
    # Печатаем название проверки.
    print("Проверка файла main_menu.py")
    # Показываем правила игры.
    show_rules()
    # Показываем главное меню и сохраняем выбор.
    choice = show_main_menu()
    # Печатаем выбор игрока.
    print(f"Выбран пункт: {choice}")
