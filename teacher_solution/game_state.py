# Берем действия меню расследования из файла данных.
from data import GAME_ACTIONS


# Создаем локальную функцию, которая печатает линию-разделитель.
def print_separator():
    # Печатаем строку из 60 символов "-".
    print("-" * 60)


# Создаем локальную функцию, которая ждет нажатия Enter.
def wait_for_enter():
    # Просим игрока нажать Enter, чтобы он успел прочитать текст.
    input("\nНажми Enter, чтобы продолжить...")


# Создаем функцию, которая делает новое состояние игры.
def create_game_state(difficulty):
    # Возвращаем словарь с текущими данными игрока.
    return {
        # Сохраняем название выбранной сложности.
        "difficulty": difficulty["name"],
        # Сохраняем количество оставшихся вопросов.
        "questions_left": difficulty["questions"],
        # Сохраняем количество оставшихся подсказок.
        "hints_left": difficulty["hints"],
        # Создаем пустой список изученных улик.
        "viewed_clues": [],
        # Создаем пустой список истории допросов.
        "question_history": [],
    }


# Создаем функцию, которая показывает меню расследования.
def show_game_menu(game_state):
    # Печатаем название текущего режима и сложность.
    print(f"\nРасследование. Сложность: {game_state['difficulty']}")
    # Печатаем количество оставшихся вопросов.
    print(f"Вопросы: {game_state['questions_left']}")
    # Печатаем количество оставшихся подсказок.
    print(f"Подсказки: {game_state['hints_left']}")
    # Печатаем разделитель.
    print_separator()
    # Перебираем все действия игрока.
    for action_key, action_text in GAME_ACTIONS.items():
        # Печатаем номер и название действия.
        print(f"{action_key}. {action_text}")
    # Получаем выбор игрока и возвращаем его.
    return input("Выбери действие: ").strip()


# Создаем функцию, которая показывает историю допросов.
def show_history(game_state):
    # Печатаем заголовок истории.
    print("\nИстория допросов")
    # Печатаем разделитель.
    print_separator()
    # Проверяем, пустая ли история допросов.
    if not game_state["question_history"]:
        # Сообщаем, что игрок еще никого не допрашивал.
        print("Ты еще никого не допрашивал.")
    # Если история не пустая, показываем записи.
    else:
        # Перебираем записи истории.
        for record in game_state["question_history"]:
            # Печатаем одну запись.
            print(f"- {record}")
    # Ждем, пока игрок прочитает историю.
    wait_for_enter()


# Проверяем, что файл запущен напрямую.
if __name__ == "__main__":
    # Печатаем название проверки.
    print("Проверка файла game_state.py")
    # Создаем тестовую сложность.
    test_difficulty = {"name": "Тест", "questions": 3, "hints": 1}
    # Создаем тестовое состояние игры.
    test_state = create_game_state(test_difficulty)
    # Печатаем созданное состояние.
    print(test_state)
    # Показываем историю на тестовом состоянии.
    show_history(test_state)
    # Показываем меню расследования на тестовом состоянии.
    choice = show_game_menu(test_state)
    # Печатаем выбор игрока.
    print(f"Выбран пункт: {choice}")
