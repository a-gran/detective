# Берем список подсказок из файла данных.
from data import HINTS


# Создаем локальную функцию, которая ждет нажатия Enter.
def wait_for_enter():
    # Просим игрока нажать Enter, чтобы он успел прочитать текст.
    input("\nНажми Enter, чтобы продолжить...")


# Создаем функцию, которая показывает подсказку.
def show_hint(game_state):
    # Проверяем, остались ли подсказки.
    if game_state["hints_left"] <= 0:
        # Сообщаем, что подсказки закончились.
        print("\nПодсказки закончились.")
        # Ждем, пока игрок прочитает сообщение.
        wait_for_enter()
        # Завершаем функцию.
        return
    # Вычисляем индекс следующей подсказки.
    hint_index = len(HINTS) - game_state["hints_left"]
    # Проверяем, не вышел ли индекс за пределы списка.
    if hint_index >= len(HINTS):
        # Используем последнюю подсказку, если подсказок меньше, чем лимит сложности.
        hint_index = len(HINTS) - 1
    # Уменьшаем количество оставшихся подсказок.
    game_state["hints_left"] -= 1
    # Печатаем подсказку.
    print(f"\nПодсказка: {HINTS[hint_index]}")
    # Печатаем количество оставшихся подсказок.
    print(f"Осталось подсказок: {game_state['hints_left']}")
    # Ждем, пока игрок прочитает подсказку.
    wait_for_enter()


# Проверяем, что файл запущен напрямую.
if __name__ == "__main__":
    # Печатаем название проверки.
    print("Проверка файла hints.py")
    # Создаем тестовое состояние игры.
    test_state = {"hints_left": 2}
    # Показываем подсказку.
    show_hint(test_state)
    # Печатаем состояние после подсказки.
    print(test_state)
